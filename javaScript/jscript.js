let currentLang = 'fr';
const typedRoles = {
  fr: ['Full-Stack Developer','Étudiant en Génie Info','Freelancer Web','Passionné du code'],
  en: ['Full-Stack Developer','Computer Eng. Student','Web Freelancer','Code Enthusiast'],
  ar: ['مطور Full-Stack','طالب هندسة معلوميات','مستقل في الويب','عاشق البرمجة']
};

function applyLang(lang) {
  const t = i18n[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if(t[key]) el.textContent = t[key];
  });
  const isRTL = lang === 'ar';
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');
  document.getElementById('lang-label').textContent = lang.toUpperCase();
  currentLang = lang;
  startTyped();
}

function setLang(lang) {
  document.getElementById('lang-overlay').style.display = 'none';
  document.getElementById('portfolio').style.display = 'block';
  applyLang(lang);
  setTimeout(initReveal, 100);
}

function showLangOverlay() {
  document.getElementById('lang-overlay').style.display = 'flex';
  document.getElementById('portfolio').style.display = 'none';
}

// TYPED
let typedIndex=0,typedCharIndex=0,typedDeleting=false,typedTimer;
function startTyped(){
  clearTimeout(typedTimer);typedIndex=0;typedCharIndex=0;typedDeleting=false;typeLoop();
}
function typeLoop(){
  const roles=typedRoles[currentLang];
  const current=roles[typedIndex%roles.length];
  const el=document.getElementById('typed-text');
  if(!el)return;
  if(!typedDeleting){
    el.textContent=current.substring(0,typedCharIndex+1);typedCharIndex++;
    if(typedCharIndex===current.length){typedDeleting=true;typedTimer=setTimeout(typeLoop,2000);return;}
  }else{
    el.textContent=current.substring(0,typedCharIndex-1);typedCharIndex--;
    if(typedCharIndex===0){typedDeleting=false;typedIndex++;}
  }
  typedTimer=setTimeout(typeLoop,typedDeleting?60:90);
}

// SCROLL REVEAL
function initReveal(){
  const els=document.querySelectorAll('.reveal');
  const obs=new IntersectionObserver((entries)=>{
    entries.forEach(e=>{if(e.isIntersecting)e.target.classList.add('visible');});
  },{threshold:0.1});
  els.forEach(el=>obs.observe(el));
}

// ACTIVE NAV
window.addEventListener('scroll',()=>{
  const sections=['hero','about','skills','projects','contact'];
  let current='hero';
  sections.forEach(id=>{
    const el=document.getElementById(id);
    if(el&&window.scrollY>=el.offsetTop-120)current=id;
  });
  document.querySelectorAll('.nav-link').forEach(l=>{
    l.classList.toggle('active',l.getAttribute('href')==='#'+current);
  });
});

// PARTICLES
const canvas=document.getElementById('bg-canvas');
const ctx=canvas.getContext('2d');
let particles=[];
function resizeCanvas(){canvas.width=window.innerWidth;canvas.height=window.innerHeight;}
class Particle{
  constructor(){this.reset();}
  reset(){
    this.x=Math.random()*canvas.width;this.y=Math.random()*canvas.height;
    this.r=Math.random()*1.5+0.3;this.vx=(Math.random()-.5)*.3;this.vy=(Math.random()-.5)*.3;
    this.alpha=Math.random()*.5+.1;this.color=Math.random()>.5?'74,222,128':'34,211,238';
  }
  update(){
    this.x+=this.vx;this.y+=this.vy;
    if(this.x<0||this.x>canvas.width||this.y<0||this.y>canvas.height)this.reset();
  }
  draw(){
    ctx.beginPath();ctx.arc(this.x,this.y,this.r,0,Math.PI*2);
    ctx.fillStyle=`rgba(${this.color},${this.alpha})`;ctx.fill();
  }
}
function initParticles(){particles=Array.from({length:120},()=>new Particle());}
function animParticles(){
  ctx.clearRect(0,0,canvas.width,canvas.height);
  particles.forEach(p=>{p.update();p.draw();});
  for(let i=0;i<particles.length;i++){
    for(let j=i+1;j<particles.length;j++){
      const dx=particles[i].x-particles[j].x,dy=particles[i].y-particles[j].y;
      const dist=Math.sqrt(dx*dx+dy*dy);
      if(dist<100){
        ctx.beginPath();ctx.strokeStyle=`rgba(74,222,128,${0.08*(1-dist/100)})`;
        ctx.lineWidth=.5;ctx.moveTo(particles[i].x,particles[i].y);ctx.lineTo(particles[j].x,particles[j].y);ctx.stroke();
      }
    }
  }
  requestAnimationFrame(animParticles);
}
resizeCanvas();initParticles();animParticles();
window.addEventListener('resize',()=>{resizeCanvas();initParticles();});

